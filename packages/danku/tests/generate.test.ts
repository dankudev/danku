import { existsSync } from "node:fs";
import { readFile, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { afterEach, beforeEach, expect, test, vi } from "vite-plus/test";

import { CliError } from "../src/error.ts";
import { compatibilityDate } from "../src/resources/cloudflare/worker.ts";
import { type Run, spawnRun } from "../src/run.ts";
import { acme, cleanUp, copy, danku, project } from "./project.ts";

const DEPLOY_TS = `const db = new D1("db");
new Worker("web", { app: "apps/web", bindings: { DB: db } });
new Worker("admin", { app: "apps/admin", domain: new Zone("acme.dev").sub("admin") });`;

/** Two SvelteKit apps on the Cloudflare adapter, one as a dependency and one as a devDependency. */
const files = {
  ...acme(DEPLOY_TS),
  "apps/web/package.json": JSON.stringify({
    devDependencies: { "@sveltejs/adapter-cloudflare": "^8.0.1" },
  }),
  "apps/admin/package.json": JSON.stringify({
    dependencies: { "@sveltejs/adapter-cloudflare": "^8.0.1" },
  }),
};

const without = (path: string) =>
  Object.fromEntries(Object.entries(files).filter(([it]) => it !== path));

const types = ["vp", ["exec", "wrangler", "types"]];
let run: ReturnType<typeof vi.fn<Run>>;
let fetch: ReturnType<typeof vi.spyOn>;

beforeEach(() => {
  // Stands in for `vp exec wrangler types`, which writes the types next to wrangler.jsonc.
  run = vi.fn<Run>(async (_command, _args, cwd) => {
    await writeFile(join(cwd, "worker-configuration.d.ts"), "interface Env {}\n");
  });
  // generate is offline: any network call fails the test.
  fetch = vi.spyOn(globalThis, "fetch");
});

afterEach(async () => {
  expect(fetch).not.toHaveBeenCalled();
  await cleanUp();
});

/** wrangler.jsonc without its generated-file comment. */
async function config(dir: string, app: string) {
  const text = await readFile(join(dir, app, "wrangler.jsonc"), "utf8");
  return JSON.parse(text.slice(text.indexOf("\n")));
}

test("writes each Worker's wrangler.jsonc and its types", async () => {
  const dir = await project(files);

  expect(await danku(["generate"], run)).toEqual({
    exitCode: 0,
    stdout: "wrote apps/web/wrangler.jsonc\nwrote apps/admin/wrangler.jsonc",
    stderr: "",
  });

  expect(await readFile(join(dir, "apps/web/wrangler.jsonc"), "utf8")).toBe(
    `// Generated by \`danku generate\` from danku/deploy.ts. Don't edit; change danku/deploy.ts instead.
{
  "$schema": "./node_modules/wrangler/config-schema.json",
  "name": "acme-web",
  "main": ".svelte-kit/cloudflare/_worker.js",
  "compatibility_date": "${compatibilityDate}",
  "compatibility_flags": [
    "nodejs_compat"
  ],
  "workers_dev": true,
  "preview_urls": false,
  "assets": {
    "binding": "ASSETS",
    "directory": ".svelte-kit/cloudflare"
  },
  "d1_databases": [
    {
      "binding": "DB",
      "database_name": "acme-db"
    }
  ]
}
`,
  );
  // A Worker on a domain is served there only.
  expect(await config(dir, "apps/admin")).toMatchObject({
    name: "acme-admin",
    workers_dev: false,
    routes: [{ pattern: "admin.acme.dev", custom_domain: true }],
    d1_databases: [],
  });
  expect(run.mock.calls).toEqual([
    [...types, join(dir, "apps/web")],
    [...types, join(dir, "apps/admin")],
  ]);
});

test("a rerun only redoes what changed", async () => {
  await project(files);
  await danku(["generate"], run);

  // Nothing changed: nothing is written, wrangler doesn't run.
  let dir = await copy(process.cwd());
  run.mockClear();
  expect(await danku(["generate"], run)).toEqual({ exitCode: 0, stdout: "", stderr: "" });
  expect(run).not.toHaveBeenCalled();

  // Missing types are regenerated without rewriting the config; a hand-edited config is replaced.
  dir = await copy(dir);
  await rm(join(dir, "apps/web/worker-configuration.d.ts"));
  await writeFile(join(dir, "apps/admin/wrangler.jsonc"), "{}");
  run.mockClear();
  expect(await danku(["generate"], run)).toEqual({
    exitCode: 0,
    stdout: "wrote apps/admin/wrangler.jsonc",
    stderr: "",
  });
  expect(run.mock.calls).toEqual([
    [...types, join(dir, "apps/web")],
    [...types, join(dir, "apps/admin")],
  ]);
  expect(await config(dir, "apps/admin")).toMatchObject({ name: "acme-admin" });
});

test("inside an app, only that app is generated", async () => {
  const dir = await project(files, "apps/web/src");

  expect(await danku(["generate"], run)).toEqual({
    exitCode: 0,
    stdout: "wrote apps/web/wrangler.jsonc",
    stderr: "",
  });
  expect(run.mock.calls).toEqual([[...types, join(dir, "apps/web")]]);
  expect(existsSync(join(dir, "apps/admin/wrangler.jsonc"))).toBe(false);
});

test("a broken setup stops before writing anything", async () => {
  const cases: { files: Record<string, string>; message: (dir: string) => string }[] = [
    {
      files: {
        ...files,
        ...acme(`${DEPLOY_TS}\nnew Worker("www", { app: "apps/web" });`),
      },
      message: () =>
        'Worker "web" and Worker "www" both use apps/web; give each Worker its own app',
    },
    {
      files: without("apps/admin/package.json"),
      message: (dir) => `Worker "admin": ${join(dir, "apps/admin/package.json")} was not found`,
    },
    {
      files: { ...files, "apps/admin/package.json": JSON.stringify({ dependencies: {} }) },
      message: () => 'Worker "admin": apps/admin must use @sveltejs/adapter-cloudflare',
    },
    // Project loading is shared with `danku deploy`, whose tests cover its other errors.
    {
      files: without("pnpm-workspace.yaml"),
      message: () =>
        "danku must run inside a pnpm workspace (no pnpm-workspace.yaml in this folder or any folder above it)",
    },
  ];

  for (const { files, message } of cases) {
    const dir = await project(files);
    expect(await danku(["generate"], run)).toEqual({
      exitCode: 1,
      stdout: "",
      stderr: message(dir),
    });
    expect(existsSync(join(dir, "apps/web/wrangler.jsonc"))).toBe(false);
  }
  expect(run).not.toHaveBeenCalled();
});

test("spawnRun runs real commands and reports how they failed", async () => {
  // The tests above replace wrangler; this checks the real process code, with Node standing in.
  const node = process.execPath;
  await spawnRun(node, ["-e", "process.exit(0)"], process.cwd());
  await expect(spawnRun(node, ["-e", "process.exit(3)"], process.cwd())).rejects.toStrictEqual(
    new CliError(`${node} -e process.exit(3) exited with code 3`),
  );
  await expect(spawnRun("danku-missing-command", [], process.cwd())).rejects.toStrictEqual(
    new CliError("danku-missing-command was not found; is it installed and on PATH?"),
  );
});
