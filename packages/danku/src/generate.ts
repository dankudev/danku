import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import { isAbsolute, join, relative } from "node:path";

import { CliError } from "./error.ts";
import { loadProject } from "./project.ts";
import { Worker, wranglerConfig } from "./resources/cloudflare/worker.ts";
import { resources } from "./resources/resource.ts";
import type { Run } from "./run.ts";

/**
 * `danku generate`: writes the files apps need from danku/deploy.ts, today each Worker's
 * wrangler.jsonc and its types. Offline: no token, no cloud calls.
 */
export async function generate(run: Run): Promise<void> {
  const { root, project } = await loadProject();
  const workers = resources.filter((resource) => resource instanceof Worker);

  // Everything is checked before the first write, so a mistake leaves no half-generated apps.
  for (const worker of workers) {
    const other = workers.find((it) => it !== worker && it.inputs.app === worker.inputs.app);
    if (other) {
      throw new CliError(
        `Worker "${worker.name}" and Worker "${other.name}" both use ${worker.inputs.app}; give each Worker its own app`,
      );
    }
    const packageFile = join(root, worker.inputs.app, "package.json");
    const pkg = (await readFile(packageFile, "utf8").then(
      (text) => JSON.parse(text),
      () => {
        throw new CliError(`Worker "${worker.name}": ${packageFile} was not found`);
      },
    )) as { dependencies?: object; devDependencies?: object };
    if (!("@sveltejs/adapter-cloudflare" in { ...pkg.dependencies, ...pkg.devDependencies })) {
      throw new CliError(
        `Worker "${worker.name}": ${worker.inputs.app} must use @sveltejs/adapter-cloudflare`,
      );
    }
  }

  // From inside an app (its scripts run there), only that app; anywhere else, all of them.
  const inside = workers.filter((worker) => {
    const path = relative(join(root, worker.inputs.app), process.cwd());
    return !path.startsWith("..") && !isAbsolute(path);
  });

  for (const worker of inside.length > 0 ? inside : workers) {
    const app = join(root, worker.inputs.app);
    const config = join(app, "wrangler.jsonc");
    const text = `// Generated by \`danku generate\` from danku/deploy.ts. Don't edit; change danku/deploy.ts instead.\n${JSON.stringify(
      wranglerConfig(worker, project),
      null,
      2,
    )}\n`;

    // Unchanged files are left alone, so watchers and caches don't see a change.
    const changed = (await readFile(config, "utf8").catch(() => "")) !== text;
    if (changed) {
      await writeFile(config, text);
      console.log(`wrote ${worker.inputs.app}/wrangler.jsonc`);
    }
    // The slow part: only when the config changed or the types were never generated.
    if (changed || !existsSync(join(app, "worker-configuration.d.ts"))) {
      await run("vp", ["exec", "wrangler", "types"], app);
    }
  }
}
